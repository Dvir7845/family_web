CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    driver BOOLEAN NOT NULL DEFAULT FALSE,
    task_manager BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type VARCHAR(31) NOT NULL,
    name VARCHAR(255),
    description VARCHAR(255),
    owner_id BIGINT REFERENCES app_users(id),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMP WITH TIME ZONE,
    completed_by_username VARCHAR(255),
    task_date DATE,
    "day" VARCHAR(20)
);

CREATE TABLE shopping_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    event_date DATE NOT NULL
);

CREATE TABLE event_invitees (
    event_id BIGINT NOT NULL REFERENCES events(id),
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    PRIMARY KEY (event_id, user_id)
);

CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE vehicle_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    booking_date DATE NOT NULL,
    slot VARCHAR(20) NOT NULL,
    CONSTRAINT unique_vehicle_slot UNIQUE (vehicle_id, booking_date, slot)
);